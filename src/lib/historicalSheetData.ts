/**
 * Mengonversi daftar SheetRowInvoicePayment ke format CSV
 */
export function convertHistoricalToCSV(): string {
  const headers = [
    'nomor_invoice',
    'nama_sekolah',
    'kode_mitra',
    'bulan',
    'tahun',
    'tahun_ajaran',
    'kategori',
    'tanggal_kirim',
    'tanggal_dibayar',
    'tagihan_full',
    'tagihan_realisasi',
    'nominal_pembayaran',
    'status_invoice',
    'status_bayar',
    'metode_bayar',
    'no_referensi',
    'keterangan'
  ];

  const rows = HISTORICAL_TRANSACTIONS_SINCE_2022.map(item => {
    return [
      `"${item.nomorInvoice}"`,
      `"${item.namaSekolah}"`,
      `"${item.kodeMitra}"`,
      `"${item.bulan}"`,
      item.tahun,
      `"${item.tahunAjaran}"`,
      `"${item.kategori}"`,
      `"${item.tanggalKirim}"`,
      `"${item.tanggalDibayar || ''}"`,
      item.tagihanFull,
      item.tagihanRealisasi,
      item.nominalPembayaran,
      `"${item.statusInvoice}"`,
      `"${item.status}"`,
      `"${item.metodeBayar || ''}"`,
      `"${item.noReferensi || ''}"`,
      `"${(item.keterangan || '').replace(/"/g, '""')}"`
    ].join(',');
  });

  return [headers.join(','), ...rows].join('\n');
}

/**
 * Mengonversi SheetRowInvoicePayment menjadi entitas Invoice dan Pembayaran
 */
export function processHistoricalDataToEntities(data: SheetRowInvoicePayment[]): {
  invoices: Invoice[];
  pembayaran: Pembayaran[];
} {
  const invoices: Invoice[] = [];
  const pembayaran: Pembayaran[] = [];

  data.forEach((row, idx) => {
    const kategoriNorm: InvoiceKategori = (row.kategori === 'Piutang Mitra' || (row.kategori as string).toLowerCase().includes('piutang') || (row.kategori as string).toLowerCase().includes('lampau'))
      ? 'Piutang Lampau'
      : (row.kategori === 'Jenjang Baru' || (row.kategori as string).toLowerCase().includes('jenjang'))
      ? 'Jenjang Baru'
      : (row.kategori === 'Franchise Fee' || (row.kategori as string).toLowerCase().includes('franchise'))
      ? 'Franchise Fee'
      : 'Renewal Fee';

    const inv: Invoice = {
      id: row.nomorInvoice,
      nomorInvoice: row.nomorInvoice,
      mitraId: row.kodeMitra,
      namaSekolah: row.namaSekolah,
      bulan: row.bulan,
      tahunAjaran: row.tahunAjaran,
      kategori: kategoriNorm,
      nominal: row.tagihanRealisasi,
      tagihanFull: row.tagihanFull,
      tagihanRealisasi: row.tagihanRealisasi,
      nominalPembayaran: row.nominalPembayaran,
      tanggalKirim: row.tanggalKirim,
      tanggalDibayar: row.tanggalDibayar,
      tanggalTerbit: row.tanggalKirim,
      jatuhTempo: `${row.tahun}-${row.bulan === 'Juli' ? '08-10' : row.bulan === 'Agustus' ? '09-15' : row.bulan === 'September' ? '10-15' : '11-15'}`,
      statusInvoice: row.statusInvoice,
      status: row.status,
      isPelaporanSaja: isSchoolPelaporanSaja(row.kodeMitra, {
        date: row.tanggalKirim,
        tahunAjaran: row.tahunAjaran,
        tahun: row.tahun,
      }),
      keterangan: row.keterangan || `Tagihan ${row.namaSekolah}`,
    };
    invoices.push(inv);

    // Jika ada pembayaran yang tercatat (> 0)
    if (row.nominalPembayaran > 0) {
      const payStatus: PembayaranStatus = row.status === 'Menunggu Konfirmasi' ? 'Menunggu Verifikasi' : 'Terverifikasi';
      const pay: Pembayaran = {
        id: `PAY-${row.tahun}${String(idx + 1).padStart(3, '0')}`,
        invoiceId: row.nomorInvoice,
        mitraId: row.kodeMitra,
        namaSekolah: row.namaSekolah,
        kategori: kategoriNorm,
        jumlah: row.nominalPembayaran,
        tanggalBayar: row.tanggalDibayar || row.tanggalKirim,
        metodeBayar: row.metodeBayar || 'Bank Mandiri Transfer',
        noReferensi: row.noReferensi || `REF-${row.tahun}-${idx + 100}`,
        buktiUrl: 'https://images.unsplash.com/photo-1554224155-8d04cb21cd6c?w=600&auto=format&fit=crop&q=60',
        status: payStatus,
        catatan: `Pembayaran ${kategoriNorm} ${row.tahunAjaran} via sheet sinkronisasi`,
      };
      pembayaran.push(pay);
    }
  });

  return { invoices, pembayaran };
}
